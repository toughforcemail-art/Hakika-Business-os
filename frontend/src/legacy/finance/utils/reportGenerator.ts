/**
 * Role-Aware Report Generator
 * Fetches live data from Supabase based on user role and generates
 * a well-structured CSV report with relevant summaries.
 */

import { supabase } from './supabase';

export interface ReportRow {
  [key: string]: string | number | boolean | null | undefined;
}

export interface ReportSection {
  heading: string;
  summary?: string; // A one-line summary stat
  rows: ReportRow[];
}

export interface ReportConfig {
  title: string;
  subtitle?: string;
  role?: string;
  generatedBy?: string;
  generatedAt?: string;
  sections: ReportSection[];
}

// ─── Helpers ─────────────────────────────────────────────────────────────────

function rowsToCSV(rows: ReportRow[]): string {
  if (rows.length === 0) return '"(No data available)"';
  const headers = Object.keys(rows[0]);
  const lines = [
    headers.map((h) => `"${h}"`).join(','),
    ...rows.map((row) =>
      headers
        .map((h) => {
          const val = row[h] ?? '';
          return `"${String(val).replace(/"/g, '""')}"`;
        })
        .join(',')
    ),
  ];
  return lines.join('\r\n');
}

function buildCSV(config: ReportConfig): string {
  const now = config.generatedAt ?? new Date().toLocaleString('en-KE', { timeZone: 'Africa/Nairobi' });
  const sep = '='.repeat(60);

  const lines: string[] = [
    `"${sep}"`,
    `"${config.title.toUpperCase()}"`,
    config.subtitle ? `"${config.subtitle}"` : '',
    `"Role: ${config.role ?? 'N/A'}"`,
    `"Generated by: ${config.generatedBy ?? 'Unknown'}"`,
    `"Generated at: ${now} (EAT)"`,
    `"${sep}"`,
    '',
  ];

  for (const section of config.sections) {
    lines.push(`"--- ${section.heading.toUpperCase()} ---"`);
    if (section.summary) {
      lines.push(`"Summary: ${section.summary}"`);
    }
    lines.push(rowsToCSV(section.rows));
    lines.push('');
  }

  lines.push(`"${sep}"`);
  lines.push(`"END OF REPORT"`);
  lines.push(`"${sep}"`);

  return lines.join('\r\n');
}

function downloadCSV(filename: string, content: string) {
  const BOM = '\uFEFF'; // UTF-8 BOM for Excel compatibility
  const blob = new Blob([BOM + content], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

