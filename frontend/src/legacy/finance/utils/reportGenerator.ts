async function fetchAdminData(): Promise<ReportSection[]> {
  const [employeesRes, departmentsRes, logsRes, incidentsRes, attendanceRes, leaveRes] =
    await Promise.all([
      supabase.from('profiles').select('id, full_name, role, department, designation, employment_type, created_at').order('created_at', { ascending: false }).limit(100),
      supabase.from('departments').select('id, name, created_at').order('created_at', { ascending: false }),
      supabase.from('activity_logs').select('user_name, action_type, action_category, description, platform, created_at').order('created_at', { ascending: false }).limit(50),
      supabase.from('security_incidents').select('id, type, severity, status, reported_at').order('reported_at', { ascending: false }).limit(50),
      supabase.from('hr_attendance').select('id, employee_id, check_in_time, check_out_time, status, date').order('date', { ascending: false }).limit(50),
      supabase.from('hr_leave_requests').select('id, employee_id, leave_type_id, status, start_date, end_date').order('created_at', { ascending: false }).limit(50),
    ]);

  const employees = employeesRes.data ?? [];
  const departments = departmentsRes.data ?? [];
  const logs = logsRes.data ?? [];
  const incidents = incidentsRes.data ?? [];
  const attendance = attendanceRes.data ?? [];
  const leave = leaveRes.data ?? [];

  // Role breakdown summary
  const roleCounts: Record<string, number> = {};
  employees.forEach((e: any) => {
    roleCounts[e.role] = (roleCounts[e.role] ?? 0) + 1;
  });

  return [
    {
      heading: 'Staff Overview',
      summary: `Total: ${employees.length} employees across ${departments.length} departments`,
      rows: employees.map((e: any) => ({
        Name: e.full_name ?? '',
        Role: e.role ?? '',
        Department: e.department ?? '',
        Designation: e.designation ?? '',
        'Employment Type': e.employment_type ?? '',
        'Joined': e.created_at ? new Date(e.created_at).toLocaleDateString('en-KE') : '',
      })),
    },
    {
      heading: 'Role Distribution',
      summary: Object.entries(roleCounts).map(([r, c]) => `${r}: ${c}`).join(' | '),
      rows: Object.entries(roleCounts).map(([Role, Count]) => ({ Role, Count })),
    },
    {
      heading: 'Departments',
      summary: `${departments.length} departments configured`,
      rows: departments.map((d: any) => ({
        Department: d.name ?? '',
        Created: d.created_at ? new Date(d.created_at).toLocaleDateString('en-KE') : '',
      })),
    },
    {
      heading: 'Recent System Activity',
      summary: `${logs.length} recent log entries`,
      rows: logs.map((l: any) => ({
        User: l.user_name ?? '',
        Action: l.action_type ?? '',
        Category: l.action_category ?? '',
        Description: l.description ?? '',
        Platform: l.platform ?? '',
        'Date/Time': l.created_at ? new Date(l.created_at).toLocaleString('en-KE') : '',
      })),
    },
    {
      heading: 'Recent Security Incidents',
      summary: `${incidents.filter((i: any) => i.status === 'open').length} open incidents`,
      rows: incidents.map((i: any) => ({
        Type: i.type ?? '',
        Severity: i.severity ?? '',
        Status: i.status ?? '',
        Reported: i.reported_at ? new Date(i.reported_at).toLocaleString('en-KE') : '',
      })),
    },
    {
      heading: 'Attendance Summary',
      summary: `${attendance.filter((a: any) => a.status === 'present').length} present out of ${attendance.length}`,
      rows: attendance.slice(0, 30).map((a: any) => ({
        Date: a.date ?? '',
        Status: a.status ?? '',
        'Clock In': a.check_in_time ? new Date(`1970-01-01T${a.check_in_time}`).toLocaleTimeString('en-KE') : '',
        'Clock Out': a.check_out_time ? new Date(`1970-01-01T${a.check_out_time}`).toLocaleTimeString('en-KE') : '',
      })),
    },
    {
      heading: 'Leave Requests',
      summary: `${leave.filter((l: any) => l.status === 'pending').length} pending approvals`,
      rows: leave.map((l: any) => ({
        'Leave Type ID': l.leave_type_id ?? '',
        'Start Date': l.start_date ?? '',
        'End Date': l.end_date ?? '',
        Status: l.status ?? '',
      })),
    },
  ];
}

